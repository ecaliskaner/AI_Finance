"""Self-contained HTML reports.

A backtest produces a wall of numbers, and the one thing you actually want to
look at — the shape of the equity curve against the thing it is supposed to beat
— is the one thing a terminal cannot show. This module renders that.

Everything is inlined: the SVG is generated here, the styles and the twenty
lines of tooltip JavaScript are in the file, and nothing is fetched from a CDN.
That is not minimalism for its own sake. The same function becomes Phase 4's
daily summary, emailed off a VPS with no browser and possibly no outbound
network, and a report that needs the internet to render is a report that will be
blank on the morning you most want to read it.

Colours come from the validated palette in the `dataviz` skill: categorical
slots 1 and 2 (blue, orange), which clear the colour-vision-deficiency and
contrast gates in both light and dark mode. The two series are also directly
labelled at the right-hand end, so identity never rests on hue alone.
"""

from __future__ import annotations

import html
import json
from dataclasses import dataclass
from functools import cache
from importlib import resources
from pathlib import Path

import numpy as np
import pandas as pd

from ai_finance.backtest.metrics import BacktestResult

#: Points kept when drawing a curve. Beyond this the SVG grows without the
#: picture changing.
MAX_POINTS = 600

_STRATEGY_COLOR = "var(--series-1)"
_BENCHMARK_COLOR = "var(--series-2)"


@dataclass(frozen=True)
class Stat:
    """One figure in the headline row."""

    label: str
    value: str
    note: str = ""
    tone: str = "neutral"  # neutral | good | bad


def write_report(
    result: BacktestResult,
    path: str | Path,
    *,
    title: str | None = None,
    subtitle: str = "",
    notes: list[str] | None = None,
) -> Path:
    """Render ``result`` to a standalone HTML file and return its path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        _document(
            result,
            title=title or f"{result.strategy_name} on {result.symbol}",
            subtitle=subtitle,
            notes=notes or [],
        ),
        encoding="utf-8",
    )
    return path


# --------------------------------------------------------------------------- #
# document
# --------------------------------------------------------------------------- #


def _document(result: BacktestResult, *, title: str, subtitle: str, notes: list[str]) -> str:
    equity = _downsample(result.equity_curve)
    benchmark = _downsample(result.benchmark_curve)
    drawdown = _downsample(_drawdown_of(result.equity_curve))
    benchmark_drawdown = _downsample(_drawdown_of(result.benchmark_curve))

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>{_asset("report.css")}</style>
</head>
<body>
<main class="viz-root">
  <header>
    <h1>{html.escape(title)}</h1>
    <p class="sub">{html.escape(subtitle)}</p>
  </header>

  <section class="stats">{_stat_tiles(result)}</section>

  <section class="chart">
    <h2>Equity</h2>
    <p class="caption">What the strategy did to the account, against holding the
      asset and doing nothing. The benchmark pays no fees, which makes it a
      deliberately hard bar.</p>
    {_legend()}
    {_line_chart(equity, benchmark, "equity", money=True)}
  </section>

  <section class="chart">
    <h2>Drawdown</h2>
    <p class="caption">Distance below the previous peak. This is the number that
      decides whether a strategy is livable, not the return.</p>
    {_legend()}
    {_line_chart(drawdown, benchmark_drawdown, "drawdown", money=False, percent=True)}
  </section>

  <section class="chart">
    <h2>Where the money went</h2>
    {_cost_table(result)}
  </section>

  <section class="chart">
    <h2>Trades</h2>
    {_trade_table(result)}
  </section>

  {_notes_block(notes)}

  <footer>
    <p>Generated by AI_Finance. Costs modelled at
      {result.costs.round_trip_cost * 10_000:.1f} bp per round trip
      ({html.escape(result.costs.describe())}).</p>
  </footer>
</main>
<script>{_asset("report.js")}</script>
</body>
</html>
"""


def _notes_block(notes: list[str]) -> str:
    if not notes:
        return ""
    items = "".join(f"<li>{html.escape(note)}</li>" for note in notes)
    return (
        '<section class="notes">'
        "<h2>Read this before believing any of it</h2>"
        f"<ul>{items}</ul></section>"
    )


def _stat_tiles(result: BacktestResult) -> str:
    beat = result.excess_return > 0
    risk_adjusted = result.beat_benchmark_risk_adjusted
    stats = [
        Stat(
            "Return",
            _pct(result.total_return),
            "after all costs",
            "good" if result.total_return > 0 else "bad",
        ),
        Stat("Benchmark", _pct(result.benchmark_return), "buy and hold, cost-free"),
        Stat(
            "Excess",
            _pct(result.excess_return),
            result.benchmark_verdict.lower(),
            "good" if beat else "bad",
        ),
        Stat(
            "Sharpe",
            _num(result.sharpe),
            f"benchmark {_num(result.benchmark_sharpe)}",
            "good" if risk_adjusted else "bad",
        ),
        Stat(
            "Max drawdown",
            _pct(result.max_drawdown),
            f"benchmark {_pct(result.benchmark_max_drawdown)}",
        ),
        # Unsigned: a cost is not a gain, and "+2.41%" reads like one.
        Stat("Cost drag", _rate(result.cost_drag), "of starting capital", "bad"),
    ]
    return "".join(
        f'<div class="tile tone-{s.tone}">'
        f'<div class="tile-label">{html.escape(s.label)}</div>'
        f'<div class="tile-value">{html.escape(s.value)}</div>'
        f'<div class="tile-note">{html.escape(s.note)}</div></div>'
        for s in stats
    )


def _legend() -> str:
    return (
        '<div class="legend">'
        f'<span class="key"><i style="background:{_STRATEGY_COLOR}"></i>Strategy</span>'
        f'<span class="key"><i style="background:{_BENCHMARK_COLOR}"></i>Buy and hold</span>'
        "</div>"
    )


def _cost_table(result: BacktestResult) -> str:
    rows = [
        ("Exchange fees", f"{result.total_fees:,.2f}"),
        ("Spread and slippage", f"{result.total_price_concession:,.2f}"),
        ("Total cost", f"{result.total_costs:,.2f}"),
        ("As a share of starting capital", _pct(result.cost_drag)),
        ("Notional traded", f"{result.turnover:.1f}x starting capital"),
        ("Fills", f"{result.n_fills:,}"),
    ]
    return _table(["", "Amount"], rows)


def _trade_table(result: BacktestResult) -> str:
    rows = [
        ("Completed round trips", f"{result.n_trades:,}"),
        ("Win rate", _rate(result.win_rate)),
        ("Average win", f"{result.avg_win:+,.2f}"),
        ("Average loss", f"{result.avg_loss:+,.2f}"),
        ("Profit factor", _num(result.profit_factor)),
        ("Time holding a position", _rate(result.exposure)),
    ]
    return _table(["", "Value"], rows)


def _table(headers: list[str], rows: list[tuple[str, str]]) -> str:
    head = "".join(f"<th>{html.escape(h)}</th>" for h in headers)
    body = "".join(
        f"<tr><td>{html.escape(label)}</td><td class='num'>{html.escape(value)}</td></tr>"
        for label, value in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


