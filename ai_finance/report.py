# chart
# --------------------------------------------------------------------------- #


def _line_chart(
    primary: pd.Series,
    secondary: pd.Series,
    chart_id: str,
    *,
    money: bool,
    percent: bool = False,
) -> str:
    """Two-series line chart as inline SVG, with a shared crosshair tooltip."""
    width, height = 1000.0, 320.0
    left, right, top, bottom = 68.0, 96.0, 16.0, 34.0
    plot_w, plot_h = width - left - right, height - top - bottom

    values = np.concatenate([primary.to_numpy(float), secondary.to_numpy(float)])
    values = values[np.isfinite(values)]
    low, high = (float(values.min()), float(values.max())) if len(values) else (0.0, 1.0)
    ticks = _nice_ticks(low, high)
    axis_low, axis_high = ticks[0], ticks[-1]
    span = axis_high - axis_low or 1.0

    times = primary.index
    n = len(times)

    def x_of(i: int) -> float:
        return left + (plot_w * i / max(n - 1, 1))

    def y_of(value: float) -> float:
        return top + plot_h * (1.0 - (value - axis_low) / span)

    grid = "".join(
        f'<line class="grid" x1="{left:.1f}" x2="{left + plot_w:.1f}" '
        f'y1="{y_of(t):.1f}" y2="{y_of(t):.1f}"/>'
        f'<text class="tick" x="{left - 10:.1f}" y="{y_of(t) + 4:.1f}" '
        f'text-anchor="end">{_axis_label(t, money, percent)}</text>'
        for t in ticks
    )

    date_positions = np.linspace(0, n - 1, min(6, n)).astype(int)
    date_axis = "".join(
        f'<text class="tick" x="{x_of(int(i)):.1f}" y="{height - 10:.1f}" '
        f'text-anchor="middle">{times[int(i)]:%b %Y}</text>'
        for i in date_positions
    )

    primary_path = _path(primary.to_numpy(float), x_of, y_of)
    secondary_path = _path(secondary.to_numpy(float), x_of, y_of)

    baseline = ""
    if axis_low < 0 < axis_high:
        baseline = (
            f'<line class="baseline" x1="{left:.1f}" x2="{left + plot_w:.1f}" '
            f'y1="{y_of(0.0):.1f}" y2="{y_of(0.0):.1f}"/>'
        )

    last_primary = float(primary.iloc[-1])
    last_secondary = float(secondary.iloc[-1])
    labels = (
        f'<text class="direct" x="{left + plot_w + 8:.1f}" y="{y_of(last_primary) + 4:.1f}">'
        f"{_axis_label(last_primary, money, percent)}</text>"
        f'<text class="direct" x="{left + plot_w + 8:.1f}" y="{y_of(last_secondary) + 4:.1f}">'
        f"{_axis_label(last_secondary, money, percent)}</text>"
    )

    payload = json.dumps(
        {
            "dates": [t.strftime("%Y-%m-%d %H:%M") for t in times],
            "primary": [_round(v) for v in primary.to_numpy(float)],
            "secondary": [_round(v) for v in secondary.to_numpy(float)],
            "left": left,
            "plotW": plot_w,
            "money": money,
            "percent": percent,
        }
    )

    return f"""<figure class="figure" data-chart='{html.escape(payload, quote=True)}'>
  <svg viewBox="0 0 {width:.0f} {height:.0f}" preserveAspectRatio="none"
       role="img" aria-label="Strategy equity against buy and hold">
    {grid}{baseline}
    <path class="series-2" d="{secondary_path}"/>
    <path class="series-1" d="{primary_path}"/>
    {labels}{date_axis}
    <line class="crosshair" y1="{top:.1f}" y2="{top + plot_h:.1f}" style="display:none"/>
    <circle class="dot dot-1" r="4" style="display:none"/>
    <circle class="dot dot-2" r="4" style="display:none"/>
    <rect class="hit" x="{left:.1f}" y="{top:.1f}"
          width="{plot_w:.1f}" height="{plot_h:.1f}" fill="transparent"/>
  </svg>
  <div class="tooltip" hidden></div>
</figure>"""


def _path(values: np.ndarray, x_of, y_of) -> str:
    parts: list[str] = []
    drawing = False
    for i, value in enumerate(values):
        if not np.isfinite(value):
            drawing = False
            continue
        command = "L" if drawing else "M"
        parts.append(f"{command}{x_of(i):.1f},{y_of(float(value)):.1f}")
        drawing = True
    return " ".join(parts)


def _drawdown_of(curve: pd.Series) -> pd.Series:
    return curve / curve.cummax() - 1.0


def _downsample(series: pd.Series, limit: int = MAX_POINTS) -> pd.Series:
    """Thin a curve for drawing, always keeping the first and last points."""
    if len(series) <= limit:
        return series
    positions = np.unique(np.linspace(0, len(series) - 1, limit).astype(int))
    return series.iloc[positions]


def _nice_ticks(low: float, high: float, target: int = 5) -> list[float]:
    """Round tick values spanning ``[low, high]``."""
    if not np.isfinite(low) or not np.isfinite(high) or high <= low:
        return [0.0, 1.0]
    raw = (high - low) / target
    magnitude = 10.0 ** np.floor(np.log10(raw))
    for multiple in (1.0, 2.0, 2.5, 5.0, 10.0):
        step = magnitude * multiple
        if raw <= step:
            break
    start = np.floor(low / step) * step
    stop = np.ceil(high / step) * step
    count = round((stop - start) / step) + 1
    return [start + i * step for i in range(count)]


def _axis_label(value: float, money: bool, percent: bool) -> str:
    if percent:
        return f"{value * 100:.0f}%"
    if money:
        return f"{value:,.0f}"
    return f"{value:.2f}"


def _round(value: float) -> float | None:
    return None if not np.isfinite(value) else round(float(value), 4)


def _pct(value: float) -> str:
    return "n/a" if not np.isfinite(value) else f"{value * 100:+.2f}%"


def _rate(value: float) -> str:
    return "n/a" if not np.isfinite(value) else f"{value * 100:.1f}%"


def _num(value: float) -> str:
    return "n/a" if not np.isfinite(value) else f"{value:.2f}"


@cache
def _asset(name: str) -> str:
    """Read a stylesheet or script from the package.

    Kept as real files rather than string literals so they can be edited with
    CSS and JavaScript tooling, and so the Python linter is not asked to hold
    opinions about stylesheet line length. They are inlined into the output at
    render time, which is what keeps the report a single portable file.
    """
    return resources.files("ai_finance.assets").joinpath(name).read_text(encoding="utf-8")
